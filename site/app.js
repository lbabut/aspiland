const toggle = document.querySelector("[data-language-toggle]");
const translatableElements = document.querySelectorAll("[data-i18n]");
const storageKey = "aspiland-language";

function applyLanguage(language) {
  const selected = translations[language] ? language : "en";
  document.documentElement.lang = selected;
  translatableElements.forEach((element) => {
    const key = element.dataset.i18n;
    const value = translations[selected][key];
    if (value) {
      element.textContent = value;
    }
  });
  toggle.textContent = selected === "en" ? "PL" : "EN";
  toggle.setAttribute("aria-label", selected === "en" ? "Przełącz na język polski" : "Switch to English");
  localStorage.setItem(storageKey, selected);
}

const storedLanguage = localStorage.getItem(storageKey);
const browserLanguage = navigator.language.toLowerCase().startsWith("pl") ? "pl" : "en";
applyLanguage(storedLanguage || browserLanguage);

toggle.addEventListener("click", () => {
  applyLanguage(document.documentElement.lang === "en" ? "pl" : "en");
});